/**
 * Writes the Android launcher icons from the same artwork as the web icons.
 *
 * Android wants two things. Older launchers take a finished square bitmap at
 * five densities; from API 26 a launcher composites a foreground layer over a
 * background colour and masks the pair into whatever shape the device uses. Both
 * come from `icon-art.mjs`, so the app on a home screen and the app in a browser
 * tab are the same mark rather than two drawings that drifted.
 *
 * Run with `npm run icons:android -w @pluralnova/web`. The output is committed.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { ADAPTIVE_BACKGROUND, adaptiveForeground, maskableIcon } from './icon-art.mjs';
import { render, toPng } from './raster.mjs';

const RES = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'android', 'app', 'src', 'main', 'res');

/**
 * Densities, as a multiple of mdpi. A legacy icon is 48dp; an adaptive
 * foreground is 108dp, of which only the middle 72dp is guaranteed to survive
 * whatever mask the launcher applies.
 */
const DENSITIES = [
  ['mdpi', 1],
  ['hdpi', 1.5],
  ['xhdpi', 2],
  ['xxhdpi', 3],
  ['xxxhdpi', 4],
];

const written = [];

function write(folder, name, art, dp, scale) {
  const size = Math.round(dp * scale);
  const dir = join(RES, folder);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, `${name}.png`), toPng(render(art, size), size));
  written.push(`${folder}/${name}.png (${size}px)`);
}

const legacy = maskableIcon();
const foreground = adaptiveForeground();

for (const [density, scale] of DENSITIES) {
  write(`mipmap-${density}`, 'ic_launcher', legacy, 48, scale);
  write(`mipmap-${density}`, 'ic_launcher_round', legacy, 48, scale);
  write(`mipmap-${density}`, 'ic_launcher_foreground', foreground, 108, scale);
}

// The Play Store listing icon, which is asked for at a fixed 512.
mkdirSync(join(RES, '..', '..', '..', '..'), { recursive: true });
writeFileSync(join(RES, '..', '..', '..', '..', 'play-store-icon.png'), toPng(render(legacy, 512), 512));
written.push('play-store-icon.png (512px)');

const anydpi = join(RES, 'mipmap-anydpi-v26');
mkdirSync(anydpi, { recursive: true });
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
`;
writeFileSync(join(anydpi, 'ic_launcher.xml'), adaptive);
writeFileSync(join(anydpi, 'ic_launcher_round.xml'), adaptive);
written.push('mipmap-anydpi-v26/ic_launcher.xml', 'mipmap-anydpi-v26/ic_launcher_round.xml');

const values = join(RES, 'values');
mkdirSync(values, { recursive: true });
writeFileSync(
  join(values, 'ic_launcher_background.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/build-android-icons.mjs; edit the artwork, not this. -->
<resources>
    <color name="ic_launcher_background">${ADAPTIVE_BACKGROUND}</color>
</resources>
`,
);
written.push('values/ic_launcher_background.xml');

console.log(`Wrote ${written.length} Android icon files:`);
for (const line of written) console.log(`  ${line}`);
